// Service Worker for BaseTeam PWA
importScripts('https://storage.googleapis.com/workbox-cdn/releases/6.4.1/workbox-sw.js');

// Set workbox config
workbox.setConfig({ debug: false });

// Background sync setup
const BACKGROUND_SYNC_QUEUE = 'background-sync-queue';

// Push notification constants
const NOTIFICATION_ICON = '/base-team-logo.jpg';
const NOTIFICATION_TITLE = 'BaseTeam';
const NOTIFICATION_OPTIONS = {
  body: 'You have new updates!',
  icon: NOTIFICATION_ICON,
  badge: '/base-team-logo.jpg',
  vibrate: [200, 100, 200, 100, 200, 100, 200],
  tag: 'base-team-notification',
  data: {
    dateOfArrival: Date.now(),
    primaryKey: 1
  },
  actions: [
    { action: 'view', title: 'View', icon: '/icons/eye.png' },
    { action: 'dismiss', title: 'Dismiss', icon: '/icons/x-mark.png' }
  ]
};

// Precache all the assets generated by your build process
workbox.precaching.precacheAndRoute(self.__WB_MANIFEST || []);

const { registerRoute } = workbox.routing;
const { StaleWhileRevalidate, CacheFirst, NetworkFirst, NetworkOnly } = workbox.strategies;
const { ExpirationPlugin } = workbox.expiration;
const { BackgroundSyncPlugin } = workbox.backgroundSync;

const CACHE_NAME = 'v1';
const OFFLINE_URL = '/offline.html';

// Install event - cache core files
self.addEventListener('install', (event) => {
  console.log('[Service Worker] Install');
  
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      console.log('[Service Worker] Caching core files');
      return cache.addAll([
        '/',
        '/index.html',
        '/manifest.json',
        '/offline.html',
        '/base-team-logo.jpg',
        '/favicon.ico',
        'https://fonts.googleapis.com/css?family=Inter:wght@300;400;500;600;700&display=swap',
        '/assets/index.ts',
      ]);
    })
  );
  self.skipWaiting();
});

// Listen for the 'install' event to show the update notification
self.addEventListener('install', (event) => {
  self.skipWaiting();
  
  const notifyClients = () => {
    self.clients.matchAll({ type: 'window' }).then(clients => {
      clients.forEach(client => {
        client.postMessage({
          type: 'SERVICE_WORKER_UPDATE',
          message: 'A new version is available!',
          timestamp: new Date().toISOString()
        });
      });
    });
  };
  
  event.waitUntil(notifyClients());
});

// Activate event - clean up old caches and take control of all clients immediately
self.addEventListener('activate', (event) => {
  console.log('[Service Worker] Activate');
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((cacheName) => {
          if (cacheName !== CACHE_NAME) {
            console.log('[Service Worker] Removing old cache:', cacheName);
            return caches.delete(cacheName);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

// Listen for messages from the client
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
  
  // Handle subscription message from the client
  if (event.data && event.data.type === 'REGISTER_PUSH_SUBSCRIPTION') {
    const subscription = event.data.subscription;
    // Here you would typically send the subscription to your server
    console.log('Received push subscription:', subscription);
    // Example: sendSubscriptionToServer(subscription);
  }
});

// Handle push events
self.addEventListener('push', (event) => {
  console.log('[Service Worker] Push received.');
  
  let notificationData = NOTIFICATION_OPTIONS;
  
  // Parse the push message data if it exists
  if (event.data) {
    try {
      const data = event.data.json();
      notificationData = {
        ...NOTIFICATION_OPTIONS,
        ...data,
        data: {
          ...NOTIFICATION_OPTIONS.data,
          ...(data.data || {})
        }
      };
    } catch (e) {
      console.log('Push message data error:', e);
      notificationData.body = event.data.text() || 'New update available!';
    }
  }
  
  const notificationPromise = self.registration.showNotification(
    notificationData.title || NOTIFICATION_TITLE,
    notificationData
  );
  
  event.waitUntil(notificationPromise);
});

// Handle notification click events
self.addEventListener('notificationclick', (event) => {
  console.log('[Service Worker] Notification click received.');
  
  // Close the notification
  event.notification.close();
  
  // Handle the action buttons
  if (event.action === 'view') {
    // Handle view action
    console.log('View action was clicked');
    // Example: Open a specific URL
    event.waitUntil(
      clients.openWindow('https://basetrello-fe.onrender.com')
    );
  } else if (event.action === 'dismiss') {
    // Handle dismiss action
    console.log('Dismiss action was clicked');
  } else {
    // Default click behavior
    event.waitUntil(
      clients.matchAll({ type: 'window' }).then((clientList) => {
        // Check if there's already a window/tab open with the app
        for (const client of clientList) {
          if (client.url === '/' && 'focus' in client) {
            return client.focus();
          }
        }
        // If no app window is open, open one
        if (clients.openWindow) {
          return clients.openWindow('/');
        }
      })
    );
  }
});

// Handle notification close events
self.addEventListener('notificationclose', (event) => {
  console.log('[Service Worker] Notification closed:', event.notification);
  // You can add any cleanup code here if needed

  // Unsubscribe from push notifications
  self.registration.pushManager.getSubscription().then((subscription) => {
    if (subscription) {
      subscription.unsubscribe().then(() => {
        console.log('Unsubscribed from push notifications');
      });
    }
  });
});

// Cache CSS and JS files with Stale-While-Revalidate strategy
registerRoute(
  ({ request }) => request.destination === 'style' || request.destination === 'script' || request.destination === 'worker',
  new StaleWhileRevalidate({
    cacheName: `${CACHE_NAME}-assets`,
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
);

// Cache images with CacheFirst strategy
registerRoute(
  ({ request }) => request.destination === 'image',
  new StaleWhileRevalidate({
    cacheName: `${CACHE_NAME}-images`,
    plugins: [
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
);

// Network first strategy for API calls
registerRoute(
  ({ url }) => url.pathname.startsWith('/v1/api/'),
  new NetworkFirst({
    cacheName: `${CACHE_NAME}-api`,
    networkTimeoutSeconds: 10,
    plugins: [
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 5 * 60, 
      }),
    ],
  })
);

// Register a route to handle failed requests
registerRoute(
  ({url}) => url.pathname.startsWith('/v1/api/'),
  new NetworkOnly({
    plugins: [
      new workbox.backgroundSync.BackgroundSyncPlugin(BACKGROUND_SYNC_QUEUE, {
        maxRetentionTime: 24 * 60,
        onSync: async ({queue}) => {
          let entry;
          while (entry = await queue.shiftRequest()) {
            try {
              await fetch(entry.request);
              console.log('Replay successful for request', entry.request);
            } catch (error) {
              console.error('Replay failed for request', entry.request, error);
              await queue.unshiftRequest(entry);
              throw new Error('Replay failed');
            }
          }
        },
      }),
    ],
  }),
  'POST' 
);

// Handle navigation requests with network first, falling back to offline page
const navigationHandler = async ({ event }) => {
  // Skip non-GET requests
  if (event.request.method !== 'GET') {
    return fetch(event.request);
  }
  try {
    // Always try to get the latest version from network first
    const networkResponse = await fetch(event.request);
    // If we got a valid response, update the cache
    const cache = await caches.open(CACHE_NAME);
    cache.put(event.request, networkResponse.clone());
    return networkResponse;
  } catch (error) {
    // If network fails, try to serve from cache
    const cachedResponse = await caches.match(event.request);
    if (cachedResponse) {
      return cachedResponse;
    }
    
    // For navigation requests, show the offline page
    if (event.request.mode === 'navigate') {
      return caches.match(OFFLINE_URL);
    }
    
    // For other requests, return a fallback response
    return new Response('You are offline, and we couldn\'t find this in the cache.', {
      status: 408,
      statusText: 'Offline',
      headers: { 'Content-Type': 'text/plain' }
    });
  }
};

registerRoute(({ request }) => request.mode === 'navigate', navigationHandler);

// Enhanced fetch event handler with better offline support
self.addEventListener('fetch', (event) => {
  if (
    event.request.method !== 'GET' || 
    event.request.url.startsWith('chrome-extension://')) {
    return;
  }
  
  if (!event.request.url.startsWith(self.location.origin)) {
    return;
  }
  
  if (event.request.url.includes('/v1/api/')) {
    event.respondWith(
      fetch(event.request)
        .then(response => {
          const responseToCache = response.clone();
          caches.open(`${CACHE_NAME}-api`)
            .then(cache => cache.put(event.request, responseToCache));
          return response;
        })
        .catch(() => {
          return caches.match(event.request)
            .then(response => response || new Response(JSON.stringify({ error: 'You are offline' }), {
              status: 503,
              statusText: 'Service Unavailable',
              headers: { 'Content-Type': 'application/json' }
            }));
        })
    );
    return;
  }
  
  // For navigation requests, use the navigation handler
  if (event.request.mode === 'navigate') {
    event.respondWith(navigationHandler({ event }));
    return;
  }
  
  // For all other requests, try cache first, then network
  // For other requests, try cache first, then network
  event.respondWith(
    caches.match(event.request).then((response) => {
      return response || fetch(event.request).catch(() => {
        // If both fail, return offline page for HTML requests
        if (event.request.headers.get('accept').includes('text/html')) {
          return caches.match(OFFLINE_URL);
        }
      });
    })
  );
});
